def nb05_instability():
    sf = "05_training_instability"
    cells = [
        title_cell(f"{sf}/05_training_instability.ipynb", "05. Training Instability, NaN/Inf & Convergence"),
        setup_cell(sf),
        imports_cell(),
        md(
            "## 1. Why Loss Goes NaN — Root Causes",
            "",
            "```",
            "Loss is NaN?",
            "  ├─ Softmax overflow? (x > 88.7 in FP32)",
            "  ├─ Division by zero in norm?",
            "  ├─ Exploding attention logits?",
            "  ├─ LR too high?",
            "  └─ Bad initialization?",
            "```",
        ),
        md(
            "## 2. Softmax Overflow & Log-Sum-Exp",
            "",
            "$e^{88.7} \\approx 1.6 \\times 10^{38}$ → FP32 overflow.",
            "",
            "**Stable softmax:** subtract $c = \\max(x)$:",
            "",
            "$$",
            "\\log\\sum_i e^{x_i} = c + \\log\\sum_i e^{x_i - c}",
            "$$",
        ),
        code(
            "def naive_softmax(x):",
            "    exp_x = torch.exp(x)",
            "    return exp_x / exp_x.sum()",
            "",
            "def stable_softmax(x):",
            "    c = x.max()",
            "    exp_x = torch.exp(x - c)",
            "    return exp_x / exp_x.sum()",
            "",
            "x = torch.tensor([1000.0, 1001.0, 999.0])",
            "print('Naive:', naive_softmax(x))  # nan",
            "print('Stable:', stable_softmax(x))",
        ),
        md(
            "## 3. Attention Instability",
            "",
            "$$",
            "\\text{Attn} = \\text{softmax}\\left(\\frac{QK^\\top}{\\sqrt{d_k}}\\right)",
            "$$",
            "",
            "If $Q, K$ grow unbounded, logits explode before softmax. **Fix:** Pre-LN, scaled dot-product, lower LR.",
        ),
        md(
            "## 4. Pre-LN vs Post-LN",
            "",
            "**Post-LN:** $x + \\text{Attn}(\\text{LN}(x))$ — gradients through LN can vanish early in training.",
            "",
            "**Pre-LN:** $\\text{LN}(x + \\text{Attn}(x))$ — better gradient norms at initialization (Xiong et al. 2020).",
        ),
        md(
            "## 5. Spectral Normalization",
            "",
            "$$",
            "\\bar{W} = \\frac{W}{\\sigma(W)}",
            "$$",
            "",
            "Constrains Lipschitz constant of linear layer → bounds gradient magnitude.",
        ),
        md(
            "## 6. Multimodal-Specific: CLIP Temperature Collapse",
            "",
            "When learnable $\\tau \\to 0$, similarities are divided by tiny $\\tau$ → logits $\\to \\pm\\infty$.",
            "",
            "**Fix:** clamp $\\tau \\geq \\tau_{min}$ (e.g. 0.01) or use fixed $\\tau = 0.07$.",
        ),
        code(
            "def clip_loss(similarities, tau):",
            "    logits = similarities / tau",
            "    labels = torch.arange(similarities.size(0))",
            "    return F.cross_entropy(logits, labels)",
            "",
            "S = torch.randn(4, 4) * 0.5",
            "for tau in [0.07, 0.001, 0.0001]:",
            "    loss = clip_loss(S, tau)",
            "    print(f'tau={tau}: loss={loss.item():.4f}')",
        ),
        code(
            "# Gradient monitor — detect instability before NaN",
            "class GradMonitor:",
            "    def __init__(self, threshold=100.0):",
            "        self.threshold = threshold",
            "    def check(self, model):",
            "        total = 0.0",
            "        for p in model.parameters():",
            "            if p.grad is not None:",
            "                total += p.grad.norm().item() ** 2",
            "        total = total ** 0.5",
            "        if total > self.threshold or np.isnan(total):",
            "            print(f'WARNING: grad norm = {total}')",
            "        return total",
            "",
            "m = nn.Linear(10, 10)",
            "x = torch.randn(4, 10) * 100  # large input -> potential instability",
            "m(x).sum().backward()",
            "GradMonitor(threshold=50).check(m)",
        ),
        md(
            "## 7. Modality Collapse",
            "",
            "One encoder receives all gradient signal; other modality ignored. **Mitigation:** balanced loss weights, gradient clipping per tower, stop-gradient on dominant branch.",
        ),
        md(
            "## 8. muP — Width-Independent Hyperparameters",
            "",
            "Scale learning rate and initialization with width so optimal $\\eta$ does not change when model width increases (Yang et al. 2022). Critical for scaling law experiments.",
        ),
        code(
            "# Reproduce softmax overflow then fix with log-sum-exp loss",
            "def log_softmax_stable(x):",
            "    c = x.max(dim=-1, keepdim=True).values",
            "    return x - c - torch.log(torch.exp(x - c).sum(dim=-1, keepdim=True))",
            "",
            "logits = torch.tensor([[1000., 1001., 999.]])",
            "print('Stable log-softmax:', log_softmax_stable(logits))",
        ),
        md(
            "## 9. Instability Fix Decision Table",
            "",
            "| Issue | Fix | Priority |",
            "|-------|-----|----------|",
            "| Softmax NaN | Log-sum-exp | Immediate |",
            "| Transformer NaN | Pre-LN | High |",
            "| CLIP NaN | Clamp tau | High |",
            "| Grad spikes | Monitor + clip | Preventive |",
        ),
        refs_cell([
            "Xiong et al. (2020) — On Layer Normalization in Transformers — [arXiv:2002.04745](https://arxiv.org/abs/2002.04745)",
            "Yang et al. (2022) — Tensor Programs V (μP) — [arXiv:2203.03466](https://arxiv.org/abs/2203.03466)",
            "Miyato et al. (2018) — Spectral Normalization — [arXiv:1802.05957](https://arxiv.org/abs/1802.05957)",
        ]),
    ]
    save(f"{sf}/05_training_instability.ipynb", cells)


def nb06_distributed():
    sf = "06_distributed_training"
    cells = [
        title_cell(f"{sf}/06_distributed_training.ipynb", "06. Distributed Training — DDP, FSDP & Parallelism"),
        setup_cell(sf),
        imports_cell(),
        md(
            "## 1. Why Distributed?",
            "",
            "$$",
            "T \\propto \\frac{N_{steps} \\cdot B_{local}}{G}",
            "$$",
            "",
            "$G$ = number of GPUs. Ideal speedup linear in $G$; communication adds overhead.",
        ),
        md(
            "## 2. Data Parallel — AllReduce",
            "",
            "$$",
            "g = \\frac{1}{G}\\sum_{g=1}^{G} g_g",
            "$$",
            "",
            "Each GPU computes gradients on local batch; AllReduce averages them.",
            "",
            "```",
            "GPU0: g0 ──┐",
            "GPU1: g1 ──┼── AllReduce ──> g = mean(g0,g1,...)",
            "GPU2: g2 ──┘",
            "```",
        ),
        md(
            "## 3. Ring AllReduce Bandwidth",
            "",
            "$$",
            "\\text{Data moved} = \\frac{2(G-1)}{G} \\cdot P \\cdot \\text{bytes}",
            "$$",
            "",
            "For $G=8$, factor $\\approx 1.75$ — nearly optimal bandwidth utilization.",
        ),
        md(
            "## 4. Model Parallelism",
            "",
            "**Tensor parallel:** split $W$ across GPUs: $Y = X[W_1 \\| W_2]$",
            "",
            "**Pipeline parallel:** micro-batches reduce bubble ratio:",
            "",
            "$$",
            "\\text{bubble} = \\frac{G-1}{G-1+M}",
            "$$",
            "",
            "$M$ = number of micro-batches.",
        ),
        code(
            "def ring_allreduce_bytes(P, G, bytes_per=4):",
            "    return 2 * (G - 1) / G * P * bytes_per",
            "",
            "P = 7_000_000_000  # 7B params",
            "for G in [2, 4, 8, 64]:",
            "    gb = ring_allreduce_bytes(P, G) / 1e9",
            "    print(f'G={G:2d}: AllReduce comm per step ≈ {gb:.2f} GB')",
        ),
        md(
            "## 5. Practical Recipes",
            "",
            "| GPUs | Recipe |",
            "|------|--------|",
            "| 1 | AMP + gradient checkpointing |",
            "| 2–8 | DDP or FSDP |",
            "| 8–64 | FSDP + tensor parallel |",
            "| 64+ | 3D parallel (data + tensor + pipeline) |",
        ),
        code(
            "# DDP skeleton (runs on CPU for demo; use cuda + init_process_group in production)",
            "import torch.nn as nn",
            "from torch.nn.parallel import DistributedDataParallel as DDP",
            "",
            "model = nn.Linear(10, 2)",
            "print('DDP wraps model; each rank gets local batch, gradients AllReduced')",
            "print('FSDP shards params + optimizer states across ranks (PyTorch 2.x)')",
            "",
            "# Effective global batch",
            "local_B, world_size = 8, 4",
            "global_B = local_B * world_size",
            "print(f'local_B={local_B}, world_size={world_size} -> global_B={global_B}')",
        ),
        code(
            "# Communication vs compute tradeoff",
            "compute_ms = 200  # forward+backward per step",
            "for G in [1, 2, 4, 8]:",
            "    P = 1e9",
            "    comm_ms = ring_allreduce_bytes(int(P), G) / 1e9 * 10  # rough: 10ms/GB",
            "    eff = compute_ms / (compute_ms/G + comm_ms) if G > 1 else 1.0",
            "    print(f'G={G}: comm~{comm_ms:.0f}ms, efficiency~{eff:.2f}x')",
        ),
        md(
            "## 6. Pipeline Parallel — Bubble Visualization",
            "",
            "```",
            "Time ->",
            "Stage0: [F0][F1][F2][F3]     (F=forward micro-batch)",
            "Stage1:     [F0][F1][F2][F3]",
            "Stage2:         [F0][F1][F2][F3]",
            "Idle (bubble) at start/end reduced by increasing micro-batches M",
            "```",
        ),
        md(
            "## 7. FSDP vs DDP",
            "",
            "| Feature | DDP | FSDP |",
            "|---------|-----|------|",
            "| Model replication | Full on each GPU | Sharded |",
            "| Memory | Highest | Lowest |",
            "| Communication | AllReduce grads | AllGather params |",
            "| Best for | Fits in VRAM | Large models |",
        ),
        code(
            "# Pipeline bubble ratio",
            "def bubble_ratio(stages, micro_batches):",
            "    return (stages - 1) / (stages - 1 + micro_batches)",
            "",
            "for M in [1, 4, 8, 16]:",
            "    b = bubble_ratio(4, M)",
            "    print(f'Stages=4, M={M:2d}: bubble={b:.1%}')",
        ),
        refs_cell([
            "Li et al. (2020) — PyTorch Distributed — [docs](https://pytorch.org/tutorials/intermediate/ddp_tutorial.html)",
            "Narayanan et al. (2021) — Megatron-LM — [arXiv:2104.04473](https://arxiv.org/abs/2104.04473)",
            "Zhao et al. (2023) — PyTorch FSDP — [PyTorch blog](https://pytorch.org/blog/introducing-pytorch-fully-sharded-data-parallel-api/)",
        ]),
    ]
    save(f"{sf}/06_distributed_training.ipynb", cells)


