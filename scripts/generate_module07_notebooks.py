            "x = torch.randn(16, 10)",
            "opt.zero_grad()",
            "with autocast(enabled=use_amp):",
            "    loss = F.cross_entropy(model(x), torch.randint(0, 2, (16,)))",
            "scaler.scale(loss).backward()",
            "scaler.step(opt); scaler.update()",
            "print(f'AMP step completed (cuda={use_amp})')",
